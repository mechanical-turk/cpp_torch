// Mechanical replay. The recording main.cpp stays unchanged; --export writes the preview.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../aliases/02-screen-long-form');
const sourcePath = path.join(repo, 'main.cpp');
const workingSource = fs.readFileSync(sourcePath, 'utf8');
const example = path.join(repo, 'scratch/examples/linear-regression');

const baseRef = '7021cfe0eb1704a31e9f429c9684d5ff66af78bd';
const base = execFileSync('git', ['show', `${baseRef}:main.cpp`], {
  cwd: repo,
  encoding: 'utf8'
});
const script = fs.readFileSync(path.join(here, 'script.md'), 'utf8');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'dlatwd-episode09-'));
const compiler = process.env.CXX || 'clang++';
const pattern = /<!-- edit: ([\w-]+) -->\s*\*\*Before\*\*\s*\x60{3}cpp\n([\s\S]*?)\n\x60{3}\s*\*\*After\*\*\s*\x60{3}cpp\n([\s\S]*?)\n\x60{3}|<!-- checkpoint: ([\w-]+) -->/g;
const steps = [...script.matchAll(pattern)];

if (steps.filter(match => match[1]).length !== [...script.matchAll(/<!-- edit:/g)].length)
  throw Error('Unparsed edits');

const seen = new Set();
const results = [];

function run(name, code) {
  const file = path.join(tmp, `${name}.cpp`);
  const executable = path.join(tmp, name);
  fs.writeFileSync(file, code);
  execFileSync(compiler, [
    '-std=c++23', '-O1', '-g', '-fsanitize=address,undefined',
    '-I', repo, file, '-o', executable
  ], {stdio: 'pipe'});
  const output = execFileSync(executable, [], {encoding: 'utf8', cwd: repo});
  results.push({name, output});
  console.log(`${name}: PASS`);
  return output;
}

run('baseline', base);
let code = base;

for (const match of steps) {
  const [, id, before, after, checkpoint] = match;
  if (id) {
    if (seen.has(id)) throw Error(`Duplicate edit ${id}`);
    seen.add(id);
    const index = code.indexOf(before);
    if (index < 0 || index !== code.lastIndexOf(before))
      throw Error(`Missing or ambiguous Before block: ${id}`);
    code = code.slice(0, index) + after + code.slice(index + before.length);
    continue;
  }

  const output = run(checkpoint, code);
  if (checkpoint === 'trained-model') {
    const weight = Number(output.match(/weight: (\S+)/)?.[1]);
    const bias = Number(output.match(/bias: (\S+)/)?.[1]);
    if (Math.abs(weight - 2) > 1e-3 || Math.abs(bias - 1) > 1e-3)
      throw Error('Training did not recover y = 2x + 1');
    console.log(output.split('Test 1\n')[0]);
  }
}

const checks = fs.readFileSync(path.join(here, 'gradient-checks.cpp'), 'utf8');
run(
  'gradient-regressions',
  code.replace('int main() {', `${checks}\nint main() {\n  gradient_checks();`)
);

const generalizationChecks = fs.readFileSync(
  path.join(here, 'generalization-checks.cpp'),
  'utf8'
);
run(
  'generalization-regressions',
  `#include <cmath>\n${code.replace(
    'int main() {',
    `${generalizationChecks}\nint main() {\n  generalization_checks();`
  )}`
);

if (fs.readFileSync(sourcePath, 'utf8') !== workingSource)
  throw Error('Recording source changed during verification');

const report = {
  baseRef,
  edits: seen.size,
  checkpoints: results.length,
  results,
  workingSourceSha256: createHash('sha256').update(workingSource).digest('hex'),
  scriptSha256: createHash('sha256').update(script).digest('hex'),
  replaySha256: createHash('sha256').update(code).digest('hex')
};

fs.writeFileSync(
  path.join(here, 'verification-run.json'),
  `${JSON.stringify(report, null, 2)}\n`
);

if (process.argv.includes('--export')) {
  fs.mkdirSync(example, {recursive: true});
  fs.writeFileSync(
    path.join(example, 'episode09.cpp'),
    `// Generated by chapter-09/verify-script.mjs from the literal script edits.\n${code}`
  );
  console.log('Exported scratch/examples/linear-regression/episode09.cpp; recording main.cpp unchanged.');
}

console.log(`Literal edits: ${seen.size}; recording source unchanged.`);
console.log(`Artifacts: ${tmp}`);
